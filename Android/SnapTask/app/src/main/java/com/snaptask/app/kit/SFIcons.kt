fun sfSymbol(name: String): ImageVector = icons[name] ?: Icons.Outlined.Circle

/** `Image(systemName:)` */
@Composable
fun SF(name: String, tint: Color, size: Dp = 20.dp, modifier: Modifier = Modifier) {
    // No Material icon has the lines inside a circle.
    if (name == "line.3.horizontal.decrease.circle") {
        androidx.compose.foundation.layout.Box(
            modifier.size(size).border(size * 0.08f, tint, androidx.compose.foundation.shape.CircleShape),
            contentAlignment = androidx.compose.ui.Alignment.Center,
        ) { Icon(sfSymbol(name), contentDescription = null, tint = tint, modifier = Modifier.size(size * 0.62f)) }
        return
    }
    Icon(sfSymbol(name), contentDescription = null, tint = tint, modifier = modifier.size(size))
}
