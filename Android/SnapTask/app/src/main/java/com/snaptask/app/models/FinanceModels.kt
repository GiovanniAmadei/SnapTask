@Serializable
enum class SubscriptionFrequency(val monthlyMultiplier: Double) {
    weekly(52.0 / 12.0),
    monthly(1.0),
    quarterly(1.0 / 3.0),
    yearly(1.0 / 12.0);

    val displayName: String get() = "sub_$name".localized

    /** The date after a charge of this frequency. */
    fun next(date: Date, steps: Int = 1): Date = when (this) {
        weekly -> date.addingDays(7 * steps)
        monthly -> date.addingMonths(steps)
        quarterly -> date.addingMonths(3 * steps)
        yearly -> date.addingYears(steps)
    }
}

@Serializable
data class FinanceEntry(
    val id: UUID = UUID.randomUUID(),
    val name: String,
    val amount: Double,
    val type: FinanceEntryType,
    val category: FinanceCategory = FinanceCategory.other,
    val customCategoryId: UUID? = null,
    val date: Date = now(),
    val notes: String? = null,
    val isRecurring: Boolean = false,
    val recurringFrequency: SubscriptionFrequency? = null,
    val recurringEndDate: Date? = null,
    val tags: List<String> = emptyList(),
    val creationDate: Date = now(),
    val lastModifiedDate: Date = now(),
) {
    val monthlyEquivalent: Double
        get() = if (isRecurring && recurringFrequency != null) amount * recurringFrequency.monthlyMultiplier else amount
    val signedAmount: Double get() = if (type.isOutflow) -amount else amount

    companion object {
        fun create(
            id: UUID = UUID.randomUUID(),
            name: String,
            amount: Double,
            type: FinanceEntryType,
            category: FinanceCategory = FinanceCategory.other,
            customCategoryId: UUID? = null,
            date: Date = now(),
            notes: String? = null,
            isRecurring: Boolean = false,
            recurringFrequency: SubscriptionFrequency? = null,
            recurringEndDate: Date? = null,
            tags: List<String> = emptyList(),
            creationDate: Date = now(),
            lastModifiedDate: Date = now(),
        ) = FinanceEntry(
            id, name, abs(amount), type, category, customCategoryId, date, notes, isRecurring,
            if (isRecurring) (recurringFrequency ?: SubscriptionFrequency.monthly) else null,
            recurringEndDate, tags, creationDate, lastModifiedDate,
        )
    }
}

