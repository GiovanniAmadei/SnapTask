/** Order and visibility of the Finance cards, stored as "trend,-summary,..." ("-" = hidden). */
data class FinanceCardLayout(val order: List<FinanceDashboardCard>, val hidden: Set<FinanceDashboardCard>) {
    val rawValue: String get() = order.joinToString(",") { if (it in hidden) "-${it.rawValue}" else it.rawValue }
    val visibleCards: List<FinanceDashboardCard> get() = order.filter { it !in hidden }

    companion object {
        const val storageKey = "financeDashboardCardLayout"
        val default = FinanceCardLayout(FinanceDashboardCard.entries.toList(), emptySet())

        fun from(rawValue: String): FinanceCardLayout {
            val order = ArrayList<FinanceDashboardCard>()
            val hidden = HashSet<FinanceDashboardCard>()
            for (token in rawValue.split(",").filter { it.isNotEmpty() }) {
                val isHidden = token.startsWith("-")
                val card = FinanceDashboardCard.entries.firstOrNull { it.rawValue == token.removePrefix("-") } ?: continue
                if (card in order) continue
                order += card
                if (isHidden) hidden += card
            }
            // Cards added in a later version go where the default order puts them.
            FinanceDashboardCard.entries.forEachIndexed { index, card ->
                if (card !in order) order.add(min(index, order.size), card)
            }
            return FinanceCardLayout(order, hidden)
        }
    }
}
