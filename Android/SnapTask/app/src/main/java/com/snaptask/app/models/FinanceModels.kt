@Serializable
data class FinancialGoal(
    val id: UUID = UUID.randomUUID(),
    val name: String,
    val targetAmount: Double,
    val currentAmount: Double = 0.0,
    val targetDate: Date? = null,
    val type: FinancialGoalType = FinancialGoalType.savings,
    val isActive: Boolean = true,
    val creationDate: Date = now(),
    val lastModifiedDate: Date = now(),
) {
    val progress: Double get() = if (targetAmount > 0) min(currentAmount / targetAmount, 1.0) else 0.0
    val remainingAmount: Double get() = max(targetAmount - currentAmount, 0.0)
    val isCompleted: Boolean get() = targetAmount > 0 && currentAmount >= targetAmount
    val monthlyNeeded: Double?
        get() {
            val target = targetDate ?: return null
            if (remainingAmount <= 0) return null
            val months = ChronoUnit.MONTHS.between(now().z(), target.z())
            return if (months > 0) remainingAmount / months else remainingAmount
        }
}

