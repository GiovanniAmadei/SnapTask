object FinanceNumber {
    /** Accepts both "," and "." as decimal separator and ignores grouping spaces. */
    fun parse(text: String): Double? {
        val cleaned = text.trim().replace(" ", "").replace(",", ".")
        val value = cleaned.toDoubleOrNull() ?: return null
        return if (value.isFinite()) value else null
    }

    fun editableText(value: Double, fractionDigits: Int = 2): String {
        val format = DecimalFormat().apply {
            decimalFormatSymbols = DecimalFormatSymbols(appLocale)
            isGroupingUsed = false
            minimumFractionDigits = 0
            maximumFractionDigits = fractionDigits
        }
        return format.format(value)
    }

    val placeholder: String
        get() = DecimalFormat("0.00", DecimalFormatSymbols(appLocale)).format(0.0)
}

